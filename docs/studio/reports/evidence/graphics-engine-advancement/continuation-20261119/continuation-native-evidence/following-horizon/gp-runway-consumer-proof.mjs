import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { pathToFileURL } from 'node:url';
const root=process.argv[2],output=process.argv[3];
const load=(relative)=>import(pathToFileURL(root+'/'+relative));
const {Simulation}=await load('src/simulation/world.ts');
const {BikeAIDriver,gpApproachSampleCount,GP_AI_HANDS}=await load('src/simulation/bike-ai.ts');
const {BikeVehicle}=await load('src/simulation/bike-vehicle.ts');
const {DEFAULT_OPTIONS,DEFAULT_SETUP}=await load('src/simulation/config.ts');
const {racingLineFor}=await load('src/simulation/racing-line.ts');
const {TrafficPlanner,personality,PASS_PACE}=await load('src/simulation/traffic.ts');
const {vehicleDefinition}=await load('src/simulation/vehicles.ts');
const {ENVELOPE_STEP}=await load('src/simulation/ai.ts');
const files=['src/simulation/ai.ts','src/simulation/bike-ai.ts','src/simulation/traffic.ts'];
const hashes=()=>Object.fromEntries(files.map(p=>[p,createHash('sha256').update(readFileSync(root+'/'+p)).digest('hex')]));
const beforeHash=hashes();
const sim=new Simulation({...DEFAULT_OPTIONS,mode:'practice',circuit:'vellamar',ruleset:'gp-motorcycle',opponents:0,vehicles:['gpr1'],seed:3303});
const bike=sim.cars[0],track=sim.track,line=racingLineFor(track);
const station=165.06075214680368,speed=68.88404586322334,freeSpeed=91.08;
bike.place(track,station,line.offsetAt(station));
bike.speed=bike.dynamics.speed=speed;
bike.body.velocity.set(bike.trackPosition.tx*speed,0,bike.trackPosition.tz*speed);
bike.dynamics.grip=bike.dynamics.frontGrip=bike.dynamics.rearGrip=1;
bike.dynamics.contactLoads={front:1250,rear:1200};
bike.dynamics.frontLoad=1250;bike.dynamics.rearLoad=1200;
const road=bike.trackPosition,slope=(line.offsetAt(station+3)-line.offsetAt(station-3))/6;
bike.dynamics.heading=Math.atan2(road.tx,road.tz)+Math.atan(slope/Math.max(.5,1-road.curvature*bike.lateral));
bike.dynamics.motoGP.lateralSpeed=0;
bike.aiOffset=line.offsetAt(station+Math.max(8,Math.min(46,6+speed*.48)));
const driver=new BikeAIDriver(bike,.988,3303);
driver.freeSpeed=freeSpeed;
const target=driver.limitSpeed(freeSpeed,track,sim.race,bike.aiOffset);
const controls=()=>({planNext:driver.planNext,planDistance:driver.planDistance,planLimit:driver.planLimit,planRecovery:driver.planRecovery,planBrake:driver.planBrake});
const normalControls=controls();
const normalProfile=[...driver.approachProfile.slice(0,driver.approachMetrics.findIndex(x=>x===0))];
const pace={...driver.passPace(track)};
const context={...driver.approachContext};
const rawCount=driver.approachMetrics.findIndex(x=>x===0),count=rawCount<0?driver.approachMetrics.length:rawCount;
const stopping=gpApproachSampleCount(Math.max(context.speed,pace.freeSpeed),bike.definition.ai.brakingBase*context.grip*bike.definition.ai.brakingMargin,track.length);
let geometric=0;
while(geometric<GP_AI_HANDS.runwayMax&&Math.abs(line.curvatureAt(bike.s+geometric))<GP_AI_HANDS.straightCurvature)geometric+=GP_AI_HANDS.runwayStep;
const inspected=Math.max(0,(count-stopping)*ENVELOPE_STEP);
const bound=Math.min(geometric,inspected);
function horizon(reference){for(let i=1;i<count&&i*ENVELOPE_STEP<bound;i++)if(driver.approachProfile[i]<reference-1)return i*ENVELOPE_STEP;return bound;}
const currentHorizon=horizon(context.speed),prospectiveHorizon=horizon(Math.max(context.speed,pace.freeSpeed));
const other=new BikeVehicle(1,'medium',DEFAULT_SETUP,'sport',vehicleDefinition('sbk1000'));
const gap=64,leaderSpeed=65;
other.place(track,station+gap,line.offsetAt(station+gap));other.speed=other.dynamics.speed=leaderSpeed;
other.body.velocity.set(other.trackPosition.tx*leaderSpeed,0,other.trackPosition.tz*leaderSpeed);
function evaluate(runway){const planner=new TrafficPlanner();const result=planner.evaluate(bike,[bike,other],track,10,8,personality(4417,0),false,line.offsetAt(station),false,s=>line.offsetAt(s),1,0,{...pace,runway});return {runway,result:{...result},blocker:planner.blocker,passTarget:planner.passTarget,limitedBy:planner.limitedBy,needDecel:planner.needDecel,slower:planner.slower};}
const rows=[evaluate(currentHorizon),evaluate(prospectiveHorizon),evaluate(PASS_PACE.settleRunway),evaluate(PASS_PACE.settleRunway-1)];
const crossings=[...driver.approachProfile.slice(0,count)].map((v,i)=>({stationDistance:i*ENVELOPE_STEP,speed:v}));
const afterHash=hashes();
const result={scope:'Read-only native planner fixture; no race simulated, source edited, or constants changed. Traffic pair is a controlled setup, not an observed fall state.',source:root,sourceUnchanged:JSON.stringify(beforeHash)===JSON.stringify(afterHash),beforeHash,afterHash,plan:{station,speed,freeSpeed,target,normalControls,afterPassingControls:controls(),normalProfile,pace,context,count,stopping,geometric,inspected,bound,currentHorizon,prospectiveHorizon},traffic:{gap,leaderSpeed,rows},profile:crossings};
writeFileSync(output,JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify({sourceUnchanged:result.sourceUnchanged,plan:{station,speed,target,normalControls,pace,count,stopping,geometric,inspected,currentHorizon,prospectiveHorizon},traffic:result.traffic},null,2));
