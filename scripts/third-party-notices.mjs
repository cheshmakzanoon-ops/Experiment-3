/**
 * Generates `public/THIRD_PARTY_NOTICES.txt`, the licence notices that ship inside the
 * build (release gate G15, docs/studio/reports/ip-audit.md). It collects:
 *
 *  - three.js (MIT)                      node_modules/three/LICENSE
 *  - Basis Universal transcoder (Apache-2.0), shipped as public/assets/basis/*
 *  - Saira + Saira Stencil One (SIL OFL 1.1)
 *  - the CC0 / CC-BY art register         public/assets/third-party/CREDITS.txt
 *  - desktop-shell runtime notes
 *
 *   node scripts/third-party-notices.mjs           # rewrite the file
 *   node scripts/third-party-notices.mjs --check   # exit 1 when the committed file is stale
 *
 * `tests/third-party-notices.test.ts` runs the same check, so a dependency bump or a new
 * CREDITS entry cannot ship with stale notices. This is an engineering aid, not legal advice.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const read = (path) => readFileSync(join(root, path), 'utf8').replace(/\r\n/g, '\n').trimEnd();
const version = (pkg) => JSON.parse(read(`node_modules/${pkg}/package.json`)).version;

/** The Apache-2.0 text ships with TypeScript (also Apache-2.0); it is the unmodified standard text. */
function apacheText() {
  const text = read('node_modules/typescript/LICENSE.txt');
  if (
    !/Apache License\s+Version 2\.0, January 2004/.test(text) ||
    !/END OF TERMS AND CONDITIONS/.test(text)
  )
    throw new Error('node_modules/typescript/LICENSE.txt is not the Apache-2.0 text');
  return text.replace(/\n{3,}/g, '\n\n');
}

/** The OFL 1.1 text starts at its banner in the Stencil One licence file. */
function oflText() {
  const text = read('src/ui/fonts/OFL-saira-stencil-one.txt');
  const start = text.indexOf('SIL OPEN FONT LICENSE Version 1.1');
  if (start < 0) throw new Error('OFL text not found');
  return text.slice(start - 62).trimStart();
}

export function buildNotices() {
  const rule = '='.repeat(78);
  const part = (title, body) => `${rule}\n${title}\n${rule}\n\n${body}\n`;
  const sections = [
    `MOTOBOUND - third-party notices

This file lists every third-party component that ships inside the MOTOBOUND build and
the licence it is distributed under. Everything not listed here (cars, bikes, riders,
tracks, buildings, interface, sound) is original work of the MOTOBOUND studio or is
generated procedurally at run time. Names such as the sponsors and tyre brands that
appear on vehicles are fictional.

Generated by scripts/third-party-notices.mjs. Release gate G15; see
docs/studio/reports/ip-audit.md.
`,
    part(
      `three.js ${version('three')} (MIT) - 3D engine, loaders and example add-ons`,
      read('node_modules/three/LICENSE'),
    ),
    part(
      'Basis Universal transcoder (Apache-2.0) - public/assets/basis/basis_transcoder.{js,wasm}',
      `Copyright Binomial LLC. Copied unmodified from three.js ${version('three')} (examples/jsm/libs/basis).
Source: https://github.com/BinomialLLC/basis_universal

${apacheText()}`,
    ),
    part(
      `Saira ${version('@fontsource-variable/saira')} and Saira Stencil One (SIL Open Font License 1.1)`,
      `Saira (variable, width + weight axes), packaged by @fontsource-variable/saira:
${read('node_modules/@fontsource-variable/saira/LICENSE').split('\n')[0]}

Saira Stencil One (src/ui/fonts/saira-stencil-one-latin-400-normal.woff2):
Copyright 2019 The Saira Stencil Project Authors (https://github.com/Omnibus-Type/Saira)

Neither font is sold by itself or renamed; the Reserved Font Name terms of the licence below apply.

${oflText()}`,
    ),
    part(
      'Photographed skies, scanned textures and baked vegetation (CC0 1.0 and CC BY 4.0)',
      `The CC BY 4.0 items below require attribution and are also credited in the game
(Paddock > Credits & licences). Licence texts: https://creativecommons.org/licenses/by/4.0/
and https://creativecommons.org/publicdomain/zero/1.0/

${read('public/assets/third-party/CREDITS.txt')}`,
    ),
    part(
      'Desktop builds (Windows / Linux / macOS)',
      `The desktop shell (desktop/) additionally redistributes Electron (MIT) and Chromium and its
dependencies; Electron's own LICENSE and LICENSES.chromium.html are packaged beside the executable
by electron-builder and must stay there. The optional Steamworks integration (steamworks.js, MIT)
loads the Steamworks redistributable only under the owner's Steamworks partner agreement; no
Steamworks binary and no Steam app id is committed to this repository.`,
    ),
  ];
  return sections.join('\n') + '\n';
}

export const NOTICES_PATH = 'public/THIRD_PARTY_NOTICES.txt';
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const next = buildNotices();
  const target = join(root, NOTICES_PATH);
  if (process.argv.includes('--check')) {
    const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
    if (current !== next) {
      console.error(`${NOTICES_PATH} is stale: run node scripts/third-party-notices.mjs`);
      process.exit(1);
    }
    console.log(`${NOTICES_PATH} is up to date (${next.length} bytes).`);
  } else {
    writeFileSync(target, next);
    console.log(`Wrote ${NOTICES_PATH} (${next.length} bytes).`);
  }
}
